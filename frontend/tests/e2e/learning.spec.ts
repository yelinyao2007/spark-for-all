import {test,expect} from '@playwright/test'
test('anonymous learner changes teaching strategy and completes a check',async({page})=>{
 await page.goto('/')
 await expect(page.getByText('离线演示模式：',{exact:false})).toBeVisible()
 await page.getByRole('button',{name:'一起想一想 ↗',exact:false}).click()
 await expect(page.getByText('简单讲解',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'↻ 再讲一次',exact:true}).click()
 await expect(page.getByText('生活类比',{exact:true})).toBeVisible()
 await expect(page.locator('.message.teacher').last()).toContainText('披萨')
 await page.getByRole('button',{name:'对',exact:true}).click()
 await expect(page.locator('.message.teacher').last()).toContainText('这次答对了')
 await page.getByRole('button',{name:'学习小结 ↗'}).click()
 await expect(page.getByText('开始理解',{exact:true})).toBeVisible()
 await expect(page.getByText('完成的小练习',{exact:true}).locator('..')).toContainText('1')
 await page.getByRole('button',{name:'回到学习空间'}).click()
 await page.getByRole('button',{name:'结束并删除本次学习'}).click()
 await expect(page.getByRole('heading',{name:/不懂，没关系。\s*我们换种方法。/})).toBeVisible()
})
test('mobile has no horizontal overflow and unavailable avatar is visible',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await page.goto('/')
 await page.getByRole('button',{name:'开始一起学习'}).click()
 await page.getByRole('button',{name:'连接 3D 星火老师'}).click()
 await expect(page.getByText('数字人尚未启用',{exact:false})).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:'test-results/mobile-learning.png',fullPage:true})
})
